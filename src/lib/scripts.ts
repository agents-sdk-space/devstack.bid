import { getTemplate } from "@/data/templates";
import type { BuilderConfig, Lang, ResolvedStep } from "./types";

/**
 * Turn resolved steps into runnable scripts. Commands are emitted as text for the
 * user to review and run locally — nothing here is ever executed by the server.
 */

const SKIP_KINDS = new Set(["longRunning", "publish", "manual"]);

function shSingleQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function psSingleQuote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function ensureTrailingNewline(text: string): string {
  return text.endsWith("\n") ? text : text + "\n";
}

function kindNote(kind: string): string {
  if (kind === "longRunning") return "Starts a long-running process — run it manually in a separate terminal:";
  if (kind === "publish") return "Publishes to a public registry — review, then run manually:";
  return "Manual step — review, then run if needed:";
}

export function toBash(steps: ResolvedStep[], config: BuilderConfig, lang: Lang = "en"): string {
  const template = getTemplate(config.templateId);
  const out: string[] = [
    "#!/usr/bin/env bash",
    `# setup.sh — generated by NVX Stack Builder`,
    `# Template: ${template?.name.en ?? config.templateId} | project: ${config.projectName}`,
    "# Review every command before running:  bash setup.sh",
    "# Long-running, publish and manual steps are commented out on purpose.",
    "",
    "# Load nvm if it is installed (it is a shell function, not a binary).",
    'export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"',
    '[ -s "$NVM_DIR/nvm.sh" ] && . "$NVM_DIR/nvm.sh"',
    "",
    "set -eo pipefail",
    "",
    "step() { printf '\\n\\033[1;36m==> %s\\033[0m\\n' \"$1\"; }",
    "verify() {",
    "  if eval \"$1\"; then printf '\\033[32m[ok] verified\\033[0m\\n';",
    "  else printf '\\033[33m[warn] verification failed: %s\\033[0m\\n' \"$1\"; fi",
    "}",
    "",
  ];
  const total = steps.length;
  steps.forEach((step, i) => {
    const title = step.title[lang];
    out.push(`# ─── ${i + 1}/${total}. ${title} ───`);
    out.push(`# ${step.explanation[lang].replace(/\n/g, " ")}`);
    if (SKIP_KINDS.has(step.kind)) {
      out.push(`# ${kindNote(step.kind)}`);
      step.commands.forEach((c) => out.push(`#   ${c}`));
      out.push("");
      return;
    }
    out.push(`step ${shSingleQuote(`${i + 1}/${total} ${title}`)}`);
    const body: string[] = [];
    for (const file of step.files) {
      if (file.path.includes("/")) body.push(`mkdir -p "$(dirname ${shSingleQuote(file.path)})"`);
      body.push(`cat > ${shSingleQuote(file.path)} <<'NVX_EOF'`);
      body.push(ensureTrailingNewline(file.content).replace(/\n$/, ""));
      body.push("NVX_EOF");
    }
    body.push(...step.commands);
    if (step.verify) body.push(`verify ${shSingleQuote(step.verify)}`);
    if (step.requires) {
      out.push(`if command -v ${step.requires} >/dev/null 2>&1; then`);
      out.push(...body); // not indented: heredoc terminators must start at column 0
      out.push("else");
      out.push(`  printf '\\033[33m[warn] %s not found — skipping. See the OS notes for this step.\\033[0m\\n' ${shSingleQuote(step.requires)}`);
      out.push("fi");
    } else {
      out.push(...body);
    }
    out.push("");
  });
  out.push("printf '\\n\\033[1;32mDone! Next: run the commented long-running step(s) above.\\033[0m\\n'");
  return out.join("\n") + "\n";
}

export function toPowerShell(steps: ResolvedStep[], config: BuilderConfig, lang: Lang = "en"): string {
  const template = getTemplate(config.templateId);
  const out: string[] = [
    "# setup.ps1 — generated by NVX Stack Builder",
    `# Template: ${template?.name.en ?? config.templateId} | project: ${config.projectName}`,
    "# Review every command, then run in PowerShell:  powershell -ExecutionPolicy Bypass -File .\\setup.ps1",
    "# Long-running, publish and manual steps are commented out on purpose.",
    "",
    '$ErrorActionPreference = "Stop"',
    "",
    "function Step([string]$Title) { Write-Host \"`n==> $Title\" -ForegroundColor Cyan }",
    "function Assert-Ok([string]$What) { if ($LASTEXITCODE -ne 0) { throw \"Failed: $What (exit $LASTEXITCODE)\" } }",
    "function Write-NvxFile([string]$Path, [string]$Content) {",
    "  $dir = Split-Path -Parent $Path",
    "  if ($dir) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }",
    "  [System.IO.File]::WriteAllText((Join-Path (Get-Location) $Path), $Content)",
    "}",
    "function Verify([scriptblock]$Check) {",
    "  try { $global:LASTEXITCODE = 0; & $Check; if ($LASTEXITCODE -ne 0) { throw 'exit code' }; Write-Host '[ok] verified' -ForegroundColor Green }",
    "  catch { Write-Warning \"verification failed: $Check\" }",
    "}",
    "",
  ];
  const total = steps.length;
  steps.forEach((step, i) => {
    const title = step.title[lang];
    out.push(`# ─── ${i + 1}/${total}. ${title} ───`);
    out.push(`# ${step.explanation[lang].replace(/\n/g, " ")}`);
    if (SKIP_KINDS.has(step.kind)) {
      out.push(`# ${kindNote(step.kind)}`);
      step.windows.forEach((c) => out.push(`#   ${c}`));
      out.push("");
      return;
    }
    out.push(`Step ${psSingleQuote(`${i + 1}/${total} ${title}`)}`);
    const body: string[] = [];
    for (const file of step.files) {
      body.push(`Write-NvxFile ${psSingleQuote(file.path)} (@'`);
      body.push(ensureTrailingNewline(file.content).replace(/\n$/, ""));
      body.push("'@ + \"`n\")");
    }
    for (const c of step.windows) {
      body.push("$global:LASTEXITCODE = 0");
      body.push(c);
      body.push(`Assert-Ok ${psSingleQuote(c)}`);
    }
    if (step.verifyWindows) body.push(`Verify { ${step.verifyWindows} }`);
    if (step.requires) {
      out.push(`if (Get-Command ${step.requires} -ErrorAction SilentlyContinue) {`);
      out.push(...body);
      out.push("} else {");
      out.push(`  Write-Warning ${psSingleQuote(`${step.requires} not found — skipping. See the OS notes for this step.`)}`);
      out.push("}");
    } else {
      out.push(...body);
    }
    out.push("");
  });
  out.push("Write-Host \"`nDone! Next: run the commented long-running step(s) above.\" -ForegroundColor Green");
  return out.join("\r\n") + "\r\n";
}

export function toReadme(steps: ResolvedStep[], config: BuilderConfig, lang: Lang = "en", shareUrl?: string): string {
  const template = getTemplate(config.templateId);
  const th = lang === "th";
  const lines: string[] = [
    `# ${config.projectName}`,
    "",
    th
      ? `สร้างด้วย **NVX Stack Builder** จากเทมเพลต **${template?.name.th ?? config.templateId}**`
      : `Generated with **NVX Stack Builder** from the **${template?.name.en ?? config.templateId}** template.`,
    "",
    th ? "## เริ่มต้นอย่างรวดเร็ว" : "## Quick start",
    "",
    "```bash",
    "# macOS / Linux / WSL",
    "bash setup.sh",
    "```",
    "",
    "```powershell",
    "# Windows PowerShell",
    "powershell -ExecutionPolicy Bypass -File .\\setup.ps1",
    "```",
    "",
    th
      ? "> ตรวจสอบสคริปต์ก่อนรันทุกครั้ง ขั้นตอนที่รันค้าง (dev server) หรือ publish จะถูกคอมเมนต์ไว้"
      : "> Always review scripts before running them. Long-running (dev server) and publish steps are commented out.",
    "",
    `- Node.js: ${config.node === "lts" ? "LTS" : config.node} (${config.jsPm})`,
    `- Python: ${config.python} (${config.pyPm})`,
    `- Add-ons: ${config.addons.join(", ") || "-"}`,
    ...(shareUrl ? ["", `${th ? "ลิงก์แชร์" : "Share link"}: ${shareUrl}`] : []),
    "",
    th ? "## ขั้นตอน" : "## Steps",
    "",
  ];
  steps.forEach((s, i) => {
    lines.push(`### ${i + 1}. ${s.title[lang]}`, "", s.explanation[lang], "");
    if (s.commands.length) lines.push("```bash", ...s.commands, "```", "");
    if (s.files.length) lines.push(`${th ? "ไฟล์" : "Files"}: ${s.files.map((f) => "`" + f.path + "`").join(", ")}`, "");
    if (s.osNotes) lines.push(`> ${s.osNotes[lang]}`, "");
    lines.push(`**${th ? "ผลลัพธ์ที่คาดหวัง" : "Expected"}:** ${s.expected[lang]}`, "");
    if (s.verify) lines.push(`**${th ? "ตรวจสอบ" : "Verify"}:** \`${s.verify}\``, "");
  });
  if (template?.nextSteps.length) {
    lines.push(th ? "## ขั้นตอนถัดไป" : "## Next steps", "");
    template.nextSteps.forEach((n) => lines.push(`- ${n[lang]}`));
    lines.push("");
  }
  return lines.join("\n");
}
