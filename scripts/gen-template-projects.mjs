// Embeds template-projects/<id>/ (complete, buildable starter projects) into
// src/data/template-projects.generated.ts so the Worker can commit them to a new repo.
// Run after editing a template project:  node scripts/gen-template-projects.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("../template-projects/", import.meta.url).pathname;
const OUT = new URL("../src/data/template-projects.generated.ts", import.meta.url).pathname;
const SKIP = new Set(["node_modules", "dist", "out", ".next"]);
// Same rule as isSeedSecretPath in src/lib/projects/template-seed.ts: never embed local env/secret files.
const SECRET = (name) => /^(\.env(\..+)?|\.dev\.vars)$/.test(name) && name !== ".env.example";

function walk(dir, base, acc) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || SECRET(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, base, acc);
    else acc.push({ path: relative(base, p), content: readFileSync(p, "utf8") });
  }
  return acc;
}

const projects = {};
for (const id of readdirSync(ROOT).sort()) if (statSync(join(ROOT, id)).isDirectory()) projects[id] = walk(join(ROOT, id), join(ROOT, id), []);
const body = `// GENERATED by scripts/gen-template-projects.mjs from template-projects/. Do not edit by hand.\n/* eslint-disable */\nexport const TEMPLATE_PROJECTS: Record<string, { path: string; content: string }[]> = ${JSON.stringify(projects, null, 1)};\n`;
if (process.argv.includes("--check")) {
  const cur = (() => { try { return readFileSync(OUT, "utf8"); } catch { return ""; } })();
  if (cur !== body) { console.error("template-projects.generated.ts is stale; run node scripts/gen-template-projects.mjs"); process.exit(1); }
} else writeFileSync(OUT, body);
console.log(Object.entries(projects).map(([k, v]) => `${k}: ${v.length} files`).join("\n"));
