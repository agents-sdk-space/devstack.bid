#!/usr/bin/env node
/**
 * studio:brand — copies the devstack.bid design system into the Studio sub-app (studio/), so
 * /studio uses the same tokens, mascot and terminal signature as the Next.js site without a
 * second source of truth. Writes studio/src/brand/* (committed, marked GENERATED):
 *   tokens.css                 = src/app/tokens.css (verbatim)
 *   brand.css                  = the `.nvx-mascot*` and `.sig*` blocks of src/app/globals.css
 *   mascot.tsx, terminal-signature.tsx, brand-icons.data.ts = src/components/brand/* with the
 *                                `@/components/ui` import pointed at ./cn and "use client" dropped
 *   cn.ts                      = src/components/ui/cn.ts
 * Usage: node scripts/sync-studio-brand.mjs [--check]   (--check exits 1 when a copy is stale;
 * tests/studio.test.ts runs it, so a brand change without a re-sync fails CI.)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "studio/src/brand");
const HEADER = (src) => `GENERATED by scripts/sync-studio-brand.mjs from ${src}. Do not edit; edit the source and re-run \`npm run studio:brand\`.`;

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");

/** Cut one `/* ---- … *\/` section of globals.css, from the comment that contains `start` to the next section comment. */
function cssSection(css, start) {
  const at = css.indexOf(start);
  if (at < 0) throw new Error(`globals.css: section "${start}" not found`);
  const begin = css.lastIndexOf("/* -----", at);
  const next = css.indexOf("\n/* -----", at);
  return css.slice(begin, next < 0 ? undefined : next).trimEnd() + "\n";
}

function tsx(src) {
  return (
    // @ts-nocheck: the source is type-checked by the Next.js app (tsconfig.json); the Studio's
    // stricter noUncheckedIndexedAccess setting would otherwise reject index reads the source guards.
    `// ${HEADER(src)}\n// @ts-nocheck -- type-checked at the source by the Next.js app.\n` +
    read(src)
      .replace(/^"use client";\s*\n/, "")
      .replace(/from "@\/components\/ui(?:\/cn)?";/g, 'from "./cn";')
  );
}

export function expectedFiles() {
  const globals = read("src/app/globals.css");
  return {
    "tokens.css": `/* ${HEADER("src/app/tokens.css")} */\n` + read("src/app/tokens.css"),
    "brand.css":
      `/* ${HEADER("src/app/globals.css")} */\n` + cssSection(globals, "NVX mascot (src/components/brand/mascot.tsx)") + "\n" + cssSection(globals, "DevStack signature (src/components/brand/terminal-signature.tsx)"),
    "mascot.tsx": tsx("src/components/brand/mascot.tsx"),
    "terminal-signature.tsx": tsx("src/components/brand/terminal-signature.tsx"),
    "brand-icons.data.ts": `// ${HEADER("src/components/brand/brand-icons.data.ts")}\n` + read("src/components/brand/brand-icons.data.ts"),
    "cn.ts": `// ${HEADER("src/components/ui/cn.ts")}\n` + read("src/components/ui/cn.ts"),
  };
}

export function staleFiles() {
  return Object.entries(expectedFiles())
    .filter(([name, body]) => {
      const p = path.join(OUT, name);
      return !fs.existsSync(p) || fs.readFileSync(p, "utf8") !== body;
    })
    .map(([name]) => name);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles();
    if (stale.length) {
      console.error(`studio brand copies are stale: ${stale.join(", ")} (run npm run studio:brand)`);
      process.exit(1);
    }
    console.log("studio:brand up to date");
  } else {
    fs.mkdirSync(OUT, { recursive: true });
    for (const [name, body] of Object.entries(expectedFiles())) fs.writeFileSync(path.join(OUT, name), body);
    console.log(`studio:brand wrote ${Object.keys(expectedFiles()).length} files to studio/src/brand`);
  }
}
