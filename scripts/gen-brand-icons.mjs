#!/usr/bin/env node
/**
 * Generates src/components/brand/brand-icons.data.ts from the `simple-icons` package (CC0-1.0 SVG data).
 * Only the icons the app uses are copied, so the client and Worker bundles stay small and
 * `simple-icons` remains a devDependency. Re-run after changing BRANDS: `node scripts/gen-brand-icons.mjs`.
 *
 * Logos are trademarks of their respective owners and are used nominatively, to identify the tools.
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

// app id -> simple-icons export name
const BRANDS = {
  node: "siNodedotjs",
  npm: "siNpm",
  pnpm: "siPnpm",
  yarn: "siYarn",
  nvm: "siNvm",
  python: "siPython",
  pypi: "siPypi",
  uv: "siUv",
  next: "siNextdotjs",
  react: "siReact",
  vite: "siVite",
  express: "siExpress",
  fastapi: "siFastapi",
  streamlit: "siStreamlit",
  typescript: "siTypescript",
  javascript: "siJavascript",
  tailwind: "siTailwindcss",
  docker: "siDocker",
  githubactions: "siGithubactions",
  vitest: "siVitest",
  eslint: "siEslint",
  pytest: "siPytest",
  ruff: "siRuff",
  pandas: "siPandas",
  plotly: "siPlotly",
  git: "siGit",
  bash: "siGnubash",
  pydantic: "siPydantic",
  socketio: "siSocketdotio",
  testinglibrary: "siTestinglibrary",
  prettier: "siPrettier",
};

const out = {};
for (const [id, name] of Object.entries(BRANDS)) {
  const icon = si[name];
  if (!icon) throw new Error(`simple-icons has no ${name}`);
  out[id] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

const body = `// GENERATED by scripts/gen-brand-icons.mjs from simple-icons (CC0-1.0). Do not edit by hand.
// Logos are trademarks of their respective owners; used only to identify the tools (see NOTICE).
export interface BrandIconData {
  title: string;
  /** Official brand colour. */
  hex: string;
  /** SVG path for a 24×24 viewBox. */
  path: string;
}

export const BRAND_ICONS = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, BrandIconData>;

export type BrandId = keyof typeof BRAND_ICONS;
`;
writeFileSync(new URL("../src/components/brand/brand-icons.data.ts", import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} brand icons`);
