#!/usr/bin/env node
// Writes wrangler.release.jsonc = wrangler.jsonc + release/build-bindings.jsonc (full release with the
// build executor). `--check` exits 1 if the committed file is stale. No secrets are read or written.
import { readFileSync, writeFileSync } from "node:fs";
import JSON5 from "json5";

export function releaseConfig(base, extra) {
  const out = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    out[k] = Array.isArray(v) && Array.isArray(base[k]) ? [...base[k], ...v] : v;
  }
  return out;
}

const root = new URL("..", import.meta.url);
const read = (p) => JSON5.parse(readFileSync(new URL(p, root), "utf8"));
const text =
  "// GENERATED by scripts/gen-release-config.mjs from wrangler.jsonc + release/build-bindings.jsonc. Do not edit.\n" +
  JSON.stringify(releaseConfig(read("wrangler.jsonc"), read("release/build-bindings.jsonc")), null, 2) + "\n";
const target = new URL("wrangler.release.jsonc", root);
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(target, "utf8"); } catch {}
  if (cur !== text) { console.error("wrangler.release.jsonc is stale: run npm run cf:release-config"); process.exit(1); }
  console.log("wrangler.release.jsonc up to date");
} else {
  writeFileSync(target, text);
  console.log("wrote wrangler.release.jsonc");
}
